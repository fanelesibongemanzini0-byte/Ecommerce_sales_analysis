-- Identify customers who made purchases in consecutive years.
WITH customer_years AS (
    SELECT DISTINCT
        customer_id,
        YEAR(order_date) AS sales_year
    FROM sales
),
customer_history AS (
    SELECT
        customer_id,
        sales_year,
        LAG(sales_year) OVER (
            PARTITION BY customer_id
            ORDER BY sales_year
        ) AS previous_purchase_year
    FROM customer_years
)
SELECT
    customer_id,
    sales_year,
    previous_purchase_year
FROM customer_history
WHERE sales_year - previous_purchase_year = 1
ORDER BY customer_id, sales_year;

