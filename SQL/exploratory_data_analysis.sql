/*
Now let's calculate Month-over-Month (MoM) revenue growth.
Write a query returning:
1. sales_year
2. sales_month
3. total_revenue
4. previous_month_revenue
5. percentage_change
*/
WITH monthly_revenue AS(
SELECT	
YEAR(order_date) AS sales_year,
MONTH(order_date) AS sales_month,
SUM(revenue) AS total_revenue,
LAG(SUM(revenue)) OVER(ORDER BY YEAR(order_date),MONTH(order_date) ) AS previous_month_revenue
FROM sales
GROUP BY sales_year,sales_month)
SELECT 
*,
ROUND((total_revenue - previous_month_revenue)/NULLIF(previous_month_revenue,0)*100,2) AS percentage_change
FROM monthly_revenue
GROUP BY sales_year,sales_month;

